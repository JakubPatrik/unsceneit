#!/usr/bin/env bash
# Writes extension/config.dev.js with the production project's secret key, so
# the popup's Debug modes work in your unpacked ("Load unpacked") build.
#
# DEV ONLY: the file is gitignored, package.sh leaves it out of store builds,
# and background.js ignores it unless the extension is loaded unpacked.
# Needs the Supabase CLI logged in and linked (in backend/).
set -euo pipefail

cd "$(dirname "$0")/.." # extension/
REF_FILE="../backend/supabase/.temp/project-ref"
[[ -f "$REF_FILE" ]] || { echo "✗ backend/ isn't linked: run supabase link there" >&2; exit 1; }
REF="$(cat "$REF_FILE")"

# --reveal: without it the CLI returns secret keys masked.
KEY="$(cd ../backend && supabase projects api-keys --project-ref "$REF" --reveal -o json | python3 -c '
import json, sys
text = sys.stdin.read()
keys = json.loads(text[text.index("["):])
print(next(k["api_key"] for k in keys if k.get("type") == "secret"))
')"

umask 077
cat > config.dev.js <<EOF
// DEV ONLY: generated by scripts/dev-setup.sh. Gitignored, never packaged.
// Lets the Debug modes call classify-frames from an unpacked build.
const DEV_SECRET_KEY = "$KEY";
EOF
echo "✓ Wrote extension/config.dev.js for project $REF. Reload the unpacked extension."
